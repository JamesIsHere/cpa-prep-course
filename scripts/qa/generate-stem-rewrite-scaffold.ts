/**
 * Generate UPDATE migration scaffold for stem rewrites (#10 citation, #11 short/no-scenario).
 * Reads candidate JSON from stdin, writes scaffold SQL to migrations dir.
 *
 * Usage: cat candidates.json | npx tsx generate-stem-rewrite-scaffold.ts --section=aud --batch=1
 */

import { writeFileSync } from "fs";
import { resolve } from "path";
import {
	getNextMigrationNumberSafe,
	getMigrationsDir,
	readStdin,
} from "./utils";

const sectionArg = process.argv
	.find((a) => a.startsWith("--section="))
	?.split("=")[1];
const batchArg = process.argv
	.find((a) => a.startsWith("--batch="))
	?.split("=")[1];

if (!sectionArg || !batchArg) {
	console.error(
		"Usage: cat candidates.json | npx tsx generate-stem-rewrite-scaffold.ts --section=aud --batch=1",
	);
	process.exit(1);
}

interface Candidate {
	id: number;
	stem: string;
	choices: string[];
	correct_index: number;
	explanation: string;
	difficulty: string;
	cognitive_level: number | null;
	topic: string;
	issues: string[];
}

async function main() {
	const input = await readStdin();
	let candidates: Candidate[];
	try {
		candidates = JSON.parse(input);
	} catch {
		console.error("Failed to parse candidate JSON from stdin");
		process.exit(1);
	}

	if (candidates.length === 0) {
		console.error("No candidates to process");
		process.exit(0);
	}

	const migNum = getNextMigrationNumberSafe();
	const filename = `${migNum}_stemfix_${sectionArg}_batch${batchArg}.sql`;
	const filepath = resolve(getMigrationsDir(), filename);

	const lines: string[] = [
		`-- Migration: Stem rewrite -- ${sectionArg.toUpperCase()} batch ${batchArg} (${candidates.length} questions)`,
		`-- Generated by generate-stem-rewrite-scaffold.ts`,
		`-- Issues: #10 (citation in stem), #11 (short/no-scenario)`,
		``,
	];

	for (const c of candidates) {
		lines.push(
			`-- Q${c.id}: ${c.topic} [${c.difficulty}/L${c.cognitive_level}]`,
		);
		lines.push(`-- Issues: ${c.issues.join(", ")}`);
		lines.push(`-- Original stem: ${c.stem.substring(0, 120)}`);
		lines.push(`UPDATE questions SET`);
		lines.push(`  stem = $EXPL$TODO: rewrite stem$EXPL$`);
		lines.push(`WHERE id = ${c.id};`);
		lines.push(``);
	}

	writeFileSync(filepath, lines.join("\n"));
	// Print path to stdout for orchestrator
	console.log(filepath);
}

main();
