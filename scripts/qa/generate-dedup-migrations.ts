/**
 * Generate DELETE migrations from duplicate cluster analysis.
 *
 * Reads the cluster JSON, excludes false-positive clusters, and writes
 * one migration file per section with DELETE statements for the losers.
 *
 * Usage:
 *   npx tsx scripts/qa/generate-dedup-migrations.ts
 *   npx tsx scripts/qa/generate-dedup-migrations.ts --dry-run
 */

import { readFileSync, writeFileSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";
import {
	getNextMigrationNumber,
	acquireMigrationLock,
	releaseMigrationLock,
	getMigrationsDir,
} from "./utils";

const __dirname = dirname(fileURLToPath(import.meta.url));
const dryRun = process.argv.includes("--dry-run");

// ─── False positive clusters (manually reviewed) ───────────────
// These are similar in wording but test genuinely different concepts.
const FALSE_POSITIVE_CLUSTERS = new Set([
	5,  // FAR Inventory: FIFO vs LIFO
	9,  // REG Deductions: "is" vs "is NOT" above-the-line
	14, // FAR PP&E: SYD 5-year vs 6-year, different calc
	18, // REG Income: "included" vs "NOT included" in gross income
	19, // REG Basis: Section 165 loss basis vs Section 1015 gain basis
	21, // REG Business Structures: LLP vs LP limited partner liability
	24, // AUD Sampling: control risk too low vs too high
	30, // FAR Equity: 10% small stock dividend vs 40% large stock dividend
	31, // AUD Evidence: most reliable vs least reliable
	32, // REG Contracts: valid contract vs valid offer
	33, // TCP Entity Formation: non-related vs 60% related shareholder
	34, // ISC SOC: CC7 System Operations vs CC9 Risk Mitigation
	42, // AUD Risks: nature vs timing vs extent — three distinct concepts
	43, // TCP Entity Formation: 100% stock vs 80% stock + bonds (boot)
	44, // AUD Sampling: incorrect acceptance vs incorrect rejection
	47, // FAR Fair Value: Level 1 vs Level 2 inputs
	58, // ISC SOC: CC2 Communication vs CC3 Risk Assessment
	60, // BAR Pension: ABO vs PBO vs VBO — different measures
	61, // FAR PP&E: impaired vs not impaired — different outcomes
	62, // ISC IT Audit: exposure factor vs ARO
	67, // AUD Understanding: when to update vs what to document
]);

// ─── Load clusters ─────────────────────────────────────────────
const clustersPath = resolve(__dirname, "../../docs/dedup-clusters.json");
const data = JSON.parse(readFileSync(clustersPath, "utf-8"));
const clusters: Array<{
	clusterId: number;
	section: string;
	topic: string;
	size: number;
	keeperId: number;
	removeIds: number[];
	maxSimilarity: number;
	questions: Array<{
		id: number;
		score: number;
		difficulty: string;
		blooms: number | null;
		stemPreview: string;
		isKeeper: boolean;
	}>;
}> = data.clusters;

// ─── Filter out false positives ────────────────────────────────
const realClusters = clusters.filter(
	(c) => !FALSE_POSITIVE_CLUSTERS.has(c.clusterId),
);

// ─── Group removals by section ─────────────────────────────────
const bySection = new Map<string, { removeIds: number[]; clusters: typeof realClusters }>();
for (const c of realClusters) {
	if (!bySection.has(c.section)) {
		bySection.set(c.section, { removeIds: [], clusters: [] });
	}
	const entry = bySection.get(c.section)!;
	entry.removeIds.push(...c.removeIds);
	entry.clusters.push(c);
}

// ─── Generate migrations ──────────────────────────────────────
const sectionOrder = ["aud", "far", "reg", "bar", "isc", "tcp"];
const migrationsDir = getMigrationsDir();

console.log(`\n=== Dedup Migration Generator ===`);
console.log(`Real clusters: ${realClusters.length} (${FALSE_POSITIVE_CLUSTERS.size} false positives excluded)`);
console.log(`Total removals: ${realClusters.reduce((s, c) => s + c.removeIds.length, 0)}`);
console.log(`Dry run: ${dryRun}\n`);

if (!dryRun) {
	acquireMigrationLock();
}

try {
	for (const section of sectionOrder) {
		const entry = bySection.get(section);
		if (!entry || entry.removeIds.length === 0) continue;

		const ids = entry.removeIds.sort((a, b) => a - b);
		const clusterDetails = entry.clusters
			.sort((a, b) => b.maxSimilarity - a.maxSimilarity);

		// Build SQL
		const lines: string[] = [];
		lines.push(`-- Deduplicate ${section.toUpperCase()} questions: remove ${ids.length} duplicates from ${clusterDetails.length} clusters`);
		lines.push(`-- Generated by analyze-duplicates.ts (threshold 0.7, false positives excluded)`);
		lines.push(`-- Keeper selection: citation > Bloom's level > explanation length > lower ID`);
		lines.push(``);

		for (const c of clusterDetails) {
			lines.push(`-- Cluster #${c.clusterId} (sim: ${c.maxSimilarity}) — ${c.topic}`);
			lines.push(`--   Keep Q${c.keeperId}`);
			const keeperQ = c.questions.find((q) => q.isKeeper)!;
			lines.push(`--     ★ Q${keeperQ.id} [${keeperQ.difficulty}, L${keeperQ.blooms ?? "?"}] ${keeperQ.stemPreview}`);
			for (const rid of c.removeIds) {
				const rq = c.questions.find((q) => q.id === rid)!;
				lines.push(`--     ✕ Q${rq.id} [${rq.difficulty}, L${rq.blooms ?? "?"}] ${rq.stemPreview}`);
			}
			lines.push(``);
		}

		lines.push(`DELETE FROM questions`);
		lines.push(`WHERE id IN (`);
		// Format IDs in rows of 10 for readability
		for (let i = 0; i < ids.length; i += 10) {
			const chunk = ids.slice(i, i + 10);
			const prefix = i === 0 ? "  " : "  ";
			const suffix = i + 10 < ids.length ? "," : "";
			lines.push(`${prefix}${chunk.join(", ")}${suffix}`);
		}
		lines.push(`);`);
		lines.push(``);
		lines.push(`-- Verify: should delete exactly ${ids.length} rows`);

		const sql = lines.join("\n");

		if (dryRun) {
			console.log(`--- ${section.toUpperCase()} (${ids.length} removals, ${clusterDetails.length} clusters) ---`);
			console.log(sql);
			console.log();
		} else {
			const num = getNextMigrationNumber();
			const filename = `${num}_dedup_${section}.sql`;
			const filepath = resolve(migrationsDir, filename);
			writeFileSync(filepath, sql + "\n");
			console.log(`Wrote ${filename} — ${ids.length} deletions from ${clusterDetails.length} clusters`);
		}
	}
} finally {
	if (!dryRun) {
		releaseMigrationLock();
	}
}

console.log(`\nDone.`);
