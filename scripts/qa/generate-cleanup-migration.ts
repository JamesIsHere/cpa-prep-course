// Generate DELETE migrations from find-duplicates-for-cleanup.ts output
// Usage: npx tsx scripts/qa/find-duplicates-for-cleanup.ts | npx tsx scripts/qa/generate-cleanup-migration.ts
//    or: npx tsx scripts/qa/generate-cleanup-migration.ts --input=cleanup-results.json
//
// Generates one migration per section: DELETE duplicates + TODOs

import { readFileSync } from "fs";
import { writeFileSync } from "fs";
import { join } from "path";
import {
	getNextMigrationNumber,
	acquireMigrationLock,
	releaseMigrationLock,
	getMigrationsDir,
} from "./utils";

const inputArg = process.argv
	.find((a) => a.startsWith("--input="))
	?.split("=")[1];

interface ClusterResult {
	keeperId: number;
	keeperStem: string;
	deleteIds: number[];
	clusterSize: number;
	topic: string;
	sampleSimilarity: number;
}

interface SectionResult {
	section: string;
	totalQuestions: number;
	todoCount: number;
	todoIds: number[];
	clusterCount: number;
	totalDuplicates: number;
	clusters: ClusterResult[];
}

async function readInput(): Promise<SectionResult[]> {
	let raw: string;
	if (inputArg) {
		raw = readFileSync(inputArg, "utf-8");
	} else {
		// Read from stdin
		const chunks: Buffer[] = [];
		for await (const chunk of process.stdin) {
			chunks.push(chunk);
		}
		raw = Buffer.concat(chunks).toString("utf-8");
	}
	return JSON.parse(raw);
}

function generateMigrationSql(result: SectionResult): string {
	const allDeleteIds: number[] = [];

	// Collect duplicate IDs
	for (const cluster of result.clusters) {
		allDeleteIds.push(...cluster.deleteIds);
	}

	// Add TODO IDs
	allDeleteIds.push(...result.todoIds);

	if (allDeleteIds.length === 0) return "";

	// Sort for deterministic output
	allDeleteIds.sort((a, b) => a - b);

	const section = result.section.toUpperCase();
	const lines: string[] = [];

	lines.push(
		`-- Cleanup: Delete ${result.totalDuplicates} duplicates + ${result.todoCount} TODOs from ${section}`,
	);
	lines.push(
		`-- Generated by find-duplicates-for-cleanup.ts (threshold 0.7, normalized trigram Jaccard)`,
	);
	lines.push(
		`-- Clusters: ${result.clusterCount} duplicate groups identified`,
	);
	lines.push(`-- Original count: ${result.totalQuestions}`);
	lines.push(
		`-- Post-cleanup: ${result.totalQuestions - allDeleteIds.length}`,
	);
	lines.push("");

	// Break into chunks of 500 IDs per DELETE statement (Postgres handles large IN lists fine,
	// but chunking makes the SQL more readable and avoids parser limits)
	const chunkSize = 500;
	for (let i = 0; i < allDeleteIds.length; i += chunkSize) {
		const chunk = allDeleteIds.slice(i, i + chunkSize);
		const chunkNum =
			allDeleteIds.length > chunkSize
				? ` (chunk ${Math.floor(i / chunkSize) + 1})`
				: "";
		lines.push(`-- Delete ${chunk.length} questions${chunkNum}`);
		lines.push(`DELETE FROM questions WHERE id IN (`);
		// Format IDs in rows of 20 for readability
		const idRows: string[] = [];
		for (let j = 0; j < chunk.length; j += 20) {
			const row = chunk.slice(j, j + 20);
			idRows.push("  " + row.join(", "));
		}
		lines.push(idRows.join(",\n"));
		lines.push(");");
		lines.push("");
	}

	return lines.join("\n");
}

async function main() {
	const results = await readInput();

	const migrationsDir = getMigrationsDir();

	acquireMigrationLock();
	try {
		for (const result of results) {
			if (result.totalDuplicates + result.todoCount === 0) {
				console.error(
					`[${result.section.toUpperCase()}] No duplicates or TODOs — skipping`,
				);
				continue;
			}

			const sql = generateMigrationSql(result);
			if (!sql) continue;

			const num = getNextMigrationNumber();
			const filename = `${num}_cleanup_duplicates_${result.section}.sql`;
			const filepath = join(migrationsDir, filename);

			writeFileSync(filepath, sql);
			console.error(
				`[${result.section.toUpperCase()}] Written ${filepath}`,
			);
			console.error(
				`  → ${result.totalDuplicates} duplicates + ${result.todoCount} TODOs = ${result.totalDuplicates + result.todoCount} deletions`,
			);
		}
	} finally {
		releaseMigrationLock();
	}

	console.error("\nDone. Review migrations before applying.");
}

main();
