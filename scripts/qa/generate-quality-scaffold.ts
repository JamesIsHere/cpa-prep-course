/**
 * Phase 2 scaffold generator — creates UPDATE SQL with TODO placeholders
 * for quality fixes (#1 giveaway longest, #3 incomplete explanation).
 *
 * Usage:
 *   cat candidates.json | npx tsx scripts/qa/generate-quality-scaffold.ts --section=aud --batch=1
 */

import { writeFileSync } from "fs";
import { resolve } from "path";
import { getNextMigrationNumberSafe, getMigrationsDir, readStdin } from "./utils";

const sectionArg = process.argv.find((a) => a.startsWith("--section="))?.split("=")[1] || "unk";
const batchArg = process.argv.find((a) => a.startsWith("--batch="))?.split("=")[1] || "1";

interface QualityCandidate {
	id: number;
	stem: string;
	choices: string[];
	correct_index: number;
	explanation: string;
	difficulty: string;
	cognitive_level: number | null;
	topic: string;
	issues: string[];
}

async function main() {
	const input = await readStdin();
	const candidates: QualityCandidate[] = JSON.parse(input);

	if (candidates.length === 0) {
		console.error("No candidates to scaffold.");
		process.exit(0);
	}

	const labels = ["A", "B", "C", "D"];
	const su = sectionArg.toUpperCase();
	const lines: string[] = [];

	lines.push(`-- Migration: Quality fix -- ${su} batch ${batchArg} (${candidates.length} questions)`);
	lines.push(`-- Generated by generate-quality-scaffold.ts`);
	lines.push(`-- Issues: #1 (giveaway longest), #3 (incomplete explanation)`);
	lines.push(``);

	for (const c of candidates) {
		const correctLabel = labels[c.correct_index];
		const choiceLens = c.choices.map((ch) => ch.split(/\s+/).length);

		lines.push(`-- Q${c.id}: ${c.topic} [${c.difficulty}/L${c.cognitive_level ?? "?"}]`);
		lines.push(`-- Issues: ${c.issues.join(", ")}`);
		lines.push(`-- STEM: ${c.stem.substring(0, 150)}`);
		lines.push(`-- CHOICES (word counts):`);
		c.choices.forEach((ch, i) => {
			const marker = i === c.correct_index ? " ★" : "  ";
			lines.push(`--   ${labels[i]}${marker} (${choiceLens[i]}w) ${ch.substring(0, 100)}`);
		});
		lines.push(`-- CURRENT EXPLANATION: ${c.explanation.substring(0, 150)}`);

		if (c.issues.includes("#1") && c.issues.includes("#3")) {
			// Both: update choices + explanation
			lines.push(`UPDATE questions SET`);
			lines.push(`  choices = $EXPL$TODO: rewrite all 4 choices — correct answer (${correctLabel}) must not be >1.8x avg wrong length, keep same correct concept$EXPL$::jsonb,`);
			lines.push(`  explanation = $EXPL$TODO: Correct (${correctLabel}): [2-3 sentences, cite standard] Wrong (${otherLabels(correctLabel)[0]}): [1-2 sentences] Wrong (${otherLabels(correctLabel)[1]}): [1-2 sentences] Wrong (${otherLabels(correctLabel)[2]}): [1-2 sentences]$EXPL$`);
			lines.push(`WHERE id = ${c.id};`);
		} else if (c.issues.includes("#1")) {
			// #1 only: update choices
			lines.push(`UPDATE questions SET`);
			lines.push(`  choices = $EXPL$TODO: rewrite all 4 choices — correct answer (${correctLabel}) must not be >1.8x avg wrong length, keep same correct concept$EXPL$::jsonb`);
			lines.push(`WHERE id = ${c.id};`);
		} else {
			// #3 only: update explanation
			lines.push(`UPDATE questions SET`);
			lines.push(`  explanation = $EXPL$TODO: Correct (${correctLabel}): [2-3 sentences, cite standard] Wrong (${otherLabels(correctLabel)[0]}): [1-2 sentences] Wrong (${otherLabels(correctLabel)[1]}): [1-2 sentences] Wrong (${otherLabels(correctLabel)[2]}): [1-2 sentences]$EXPL$`);
			lines.push(`WHERE id = ${c.id};`);
		}
		lines.push(``);
	}

	const sql = lines.join("\n");
	const num = getNextMigrationNumberSafe(`quality_${sectionArg}_batch${batchArg}`);
	const filename = `${num}_quality_${sectionArg}_batch${batchArg}.sql`;
	const filepath = resolve(getMigrationsDir(), filename);
	writeFileSync(filepath, sql + "\n");

	// Output path for orchestrator
	console.log(filepath);
	console.error(`Wrote ${filename} — ${candidates.length} questions`);
}

function otherLabels(correct: string): string[] {
	return ["A", "B", "C", "D"].filter((l) => l !== correct);
}

main().catch((err) => {
	console.error(err);
	process.exit(1);
});
