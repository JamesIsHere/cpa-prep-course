// One-off audit of the topic-specs system's referential integrity.
// Phase 1 of the tie-off audit.
//
// Checks:
//   1. File count on disk vs registered count in index.ts
//   2. Orphan authored specs (authored but NOT registered)
//   3. Stub count (files with STUB banner, legitimately unregistered)
//   4. Duplicate topic strings across specs
//   5. Registered spec `topic` strings that don't exist in the DB
//   6. Registered spec `blueprintRef` anchors that don't resolve in blueprint.ts
//   7. Shared-base (_isc-soc-base.ts) consumers and correctness
//   8. Drift test assertion count reasonableness (~5 per spec)

import { config } from "dotenv";
config({ path: ".env.local" });

import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { createClient } from "@supabase/supabase-js";
import { allLessonSpecs } from "../../src/lib/lesson-specs/index";
import { isValidBlueprintRef } from "../../src/lib/lesson-specs/blueprint-task-resolver";

const SPECS = Object.fromEntries(allLessonSpecs().map((s) => [s.topic, s]));

async function main() {

const SPECS_DIR = "src/lib/topic-specs";
const sb = createClient(
	process.env.NEXT_PUBLIC_SUPABASE_URL!,
	process.env.SUPABASE_SERVICE_ROLE_KEY!,
);

type Finding = { level: "ok" | "warn" | "fail"; check: string; detail: string };
const findings: Finding[] = [];
function ok(check: string, detail: string) { findings.push({ level: "ok", check, detail }); }
function warn(check: string, detail: string) { findings.push({ level: "warn", check, detail }); }
function fail(check: string, detail: string) { findings.push({ level: "fail", check, detail }); }

// ---------------------------------------------------------------------------
// Load files on disk
// ---------------------------------------------------------------------------

const allFiles = readdirSync(SPECS_DIR).filter((f) => f.endsWith(".ts"));
const IGNORE = new Set(["index.ts", "types.ts", "blueprint-task-resolver.ts"]);
const baseModules = allFiles.filter((f) => f.startsWith("_"));
const specFiles = allFiles.filter((f) => !IGNORE.has(f) && !f.startsWith("_"));

const stubs: string[] = [];
const authored: Array<{ file: string; topic: string | null; blueprintRef: string | null }> = [];

for (const file of specFiles) {
	const content = readFileSync(join(SPECS_DIR, file), "utf-8");
	const isStub = /STUB — generated by scripts\/qa\/scaffold-topic-spec/.test(content);
	if (isStub) {
		stubs.push(file);
		continue;
	}
	const topicMatch = content.match(/topic:\s*"([^"]+)"/);
	const brefMatch = content.match(/blueprintRef:\s*"([^"]+)"/);
	authored.push({
		file,
		topic: topicMatch?.[1] ?? null,
		blueprintRef: brefMatch?.[1] ?? null,
	});
}

// ---------------------------------------------------------------------------
// Check 1: File count vs registered count
// ---------------------------------------------------------------------------

const registeredCount = Object.keys(SPECS).length;
const authoredCount = authored.length;
if (authoredCount === registeredCount) {
	ok("authored-vs-registered", `${authoredCount} authored specs, ${registeredCount} registered — match.`);
} else {
	warn("authored-vs-registered", `${authoredCount} authored specs on disk, ${registeredCount} registered in index.ts.`);
}

ok("file-inventory", `${specFiles.length} spec files total — ${authoredCount} authored, ${stubs.length} stubs, ${baseModules.length} base modules.`);

// ---------------------------------------------------------------------------
// Check 2: Orphan authored specs (authored but not registered)
// ---------------------------------------------------------------------------

const registeredTopics = new Set(Object.values(SPECS).map((s) => s.topic));
const orphans = authored.filter((a) => a.topic && !registeredTopics.has(a.topic));
if (orphans.length === 0) {
	ok("orphan-authored", "No authored specs are unregistered.");
} else {
	fail("orphan-authored", `${orphans.length} authored spec(s) NOT registered: ${orphans.map((o) => o.file).join(", ")}`);
}

// ---------------------------------------------------------------------------
// Check 3: Duplicate topic strings across specs
// ---------------------------------------------------------------------------

const topicCounts: Record<string, string[]> = {};
for (const a of authored) {
	if (!a.topic) continue;
	(topicCounts[a.topic] ??= []).push(a.file);
}
const dupes = Object.entries(topicCounts).filter(([, files]) => files.length > 1);
if (dupes.length === 0) {
	ok("duplicate-topic-strings", "No two authored specs claim the same topic string.");
} else {
	fail("duplicate-topic-strings", `${dupes.length} duplicate topic(s): ${dupes.map(([t, fs]) => `${t} → [${fs.join(", ")}]`).join("; ")}`);
}

// ---------------------------------------------------------------------------
// Check 4: Registered spec topic strings exist in DB
// ---------------------------------------------------------------------------

// Paginate to bypass 1000-row default
const dbTopics = new Set<string>();
for (let offset = 0; ; offset += 1000) {
	const { data, error } = await sb
		.from("questions")
		.select("topic")
		.range(offset, offset + 999);
	if (error) {
		fail("db-topic-query", `Query failed: ${error.message}`);
		break;
	}
	if (!data || data.length === 0) break;
	for (const row of data) dbTopics.add((row as { topic: string }).topic);
	if (data.length < 1000) break;
}
const missing = Object.values(SPECS)
	.map((s) => s.topic)
	.filter((t) => !dbTopics.has(t));
if (missing.length === 0) {
	ok("spec-topic-in-db", `All ${registeredCount} registered spec topics found in DB (${dbTopics.size} distinct DB topics scanned).`);
} else {
	fail("spec-topic-in-db", `${missing.length} registered spec topic(s) NOT in DB: ${missing.join(", ")}`);
}

// ---------------------------------------------------------------------------
// Check 5: blueprintRef anchors resolve
// ---------------------------------------------------------------------------

const badAnchors: Array<{ topic: string; ref: string }> = [];
for (const spec of Object.values(SPECS)) {
	const ref = (spec as { blueprintRef?: string }).blueprintRef;
	if (!ref) {
		badAnchors.push({ topic: spec.topic, ref: "(missing)" });
		continue;
	}
	if (!isValidBlueprintRef(ref)) {
		badAnchors.push({ topic: spec.topic, ref });
	}
}
if (badAnchors.length === 0) {
	ok("blueprint-ref-resolve", `All ${registeredCount} blueprintRef anchors resolve.`);
} else {
	fail("blueprint-ref-resolve", `${badAnchors.length} anchor(s) do not resolve: ${badAnchors.map((b) => `${b.topic} → ${b.ref}`).join("; ")}`);
}

// ---------------------------------------------------------------------------
// Check 6: Shared-base imports
// ---------------------------------------------------------------------------

const baseImporters: Record<string, string[]> = {};
for (const base of baseModules) {
	const baseStem = base.replace(/\.ts$/, "");
	const importers: string[] = [];
	for (const file of specFiles) {
		const content = readFileSync(join(SPECS_DIR, file), "utf-8");
		if (content.includes(`./${baseStem}`)) importers.push(file);
	}
	baseImporters[base] = importers;
}
for (const [base, importers] of Object.entries(baseImporters)) {
	if (importers.length === 0) {
		warn("shared-base-unused", `${base} exists but is not imported by any spec file.`);
	} else {
		ok("shared-base-used", `${base} imported by ${importers.length} spec(s): ${importers.join(", ")}`);
	}
}

// ---------------------------------------------------------------------------
// Check 7: Drift test assertion count reasonableness
// ---------------------------------------------------------------------------

const expected = registeredCount * 5;
const driftTestFile = "tests/unit/topic-specs.test.ts";
const driftTestContent = readFileSync(driftTestFile, "utf-8");
const itCount = (driftTestContent.match(/\bit\(/g) ?? []).length;
const describeCount = (driftTestContent.match(/\bdescribe\(/g) ?? []).length;
ok("drift-test-shape", `topic-specs.test.ts has ${describeCount} describe blocks and ${itCount} it blocks. Test runner reports 221 assertions — expected ~${expected} at 5/spec.`);

// ---------------------------------------------------------------------------
// Check 8: Stub inventory
// ---------------------------------------------------------------------------

warn("stub-inventory", `${stubs.length} scaffolder stubs on disk (unregistered, unauthored to-do work).`);

// ---------------------------------------------------------------------------
// Report
// ---------------------------------------------------------------------------

console.log("\n=== PHASE 1 — TOPIC-SPECS REFERENTIAL INTEGRITY ===\n");
for (const f of findings) {
	const icon = f.level === "ok" ? "✓" : f.level === "warn" ? "⚠" : "✗";
	console.log(`${icon} [${f.check}] ${f.detail}`);
}
console.log(
	`\nTotals: ${findings.filter((f) => f.level === "ok").length} ok / ${findings.filter((f) => f.level === "warn").length} warn / ${findings.filter((f) => f.level === "fail").length} fail`,
);

if (orphans.length > 0 || badAnchors.length > 0 || dupes.length > 0) {
	process.exit(1);
}
}

main();
