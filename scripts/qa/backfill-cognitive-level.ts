// Backfill cognitive_level column using Bloom's heuristic classifier
// Generates a SQL migration file for human review before applying
// Usage: tsx scripts/qa/backfill-cognitive-level.ts

import { writeFileSync } from "fs";
import { dirname, resolve } from "path";
import { fileURLToPath } from "url";
import { classifyBloomsLevel } from "./analyzers/blooms";
import { fetchAllQuestions } from "./db-client";

const __dirname = dirname(fileURLToPath(import.meta.url));

async function main() {
	console.log("Fetching all questions...");
	const questions = await fetchAllQuestions();
	console.log(`Classifying ${questions.length} questions...\n`);

	// Classify each question
	const byLevel = new Map<number, number[]>();
	let highConfidence = 0;
	let mediumConfidence = 0;
	let lowConfidence = 0;

	for (const q of questions) {
		const { level, confidence } = classifyBloomsLevel(q.stem);
		if (!byLevel.has(level)) byLevel.set(level, []);
		byLevel.get(level)!.push(q.id);

		if (confidence === "high") highConfidence++;
		else if (confidence === "medium") mediumConfidence++;
		else lowConfidence++;
	}

	// Print summary
	console.log("Classification summary:");
	for (const [level, ids] of [...byLevel.entries()].sort()) {
		const pct = Math.round((ids.length / questions.length) * 100);
		console.log(`  L${level}: ${ids.length} questions (${pct}%)`);
	}
	console.log(
		`\nConfidence: ${highConfidence} high, ${mediumConfidence} medium, ${lowConfidence} low`,
	);

	// Generate SQL migration
	const lines: string[] = [];
	lines.push(
		"-- Backfill cognitive_level based on heuristic Bloom's classification",
	);
	lines.push("-- Generated by: tsx scripts/qa/backfill-cognitive-level.ts");
	lines.push(`-- Date: ${new Date().toISOString().split("T")[0]}`);
	lines.push(`-- Total questions: ${questions.length}`);
	lines.push(`-- Accuracy estimate: ~70-80% (heuristic-based)`);
	lines.push("");

	for (const [level, ids] of [...byLevel.entries()].sort()) {
		lines.push(`-- Level ${level}: ${ids.length} questions`);

		// Batch in groups of 500 to avoid overly long IN clauses
		for (let i = 0; i < ids.length; i += 500) {
			const batch = ids.slice(i, i + 500);
			lines.push(
				`UPDATE questions SET cognitive_level = ${level} WHERE id IN (${batch.join(", ")});`,
			);
		}
		lines.push("");
	}

	const migrationPath = resolve(
		__dirname,
		"../../supabase/migrations/00039_backfill_cognitive_levels.sql",
	);
	writeFileSync(migrationPath, lines.join("\n"));
	console.log(`\nMigration written to: ${migrationPath}`);
	console.log("Review the file before applying with: supabase db push");
}

main().catch((err) => {
	console.error("Fatal error:", err);
	process.exit(1);
});
